from typing import Literal, Optional
from pydantic import BaseModel, Field

ResolutionType = Literal["1080p", "720p", "540p", "480p"]


class StreamOfferRequest(BaseModel):
    """Client WebRTC SDP offer request to initiate desktop video streaming."""
    sdp: str = Field(description="WebRTC Session Description Protocol (SDP) offer string")
    type: Literal["offer"] = Field(default="offer", description="SDP message type")
    fps: int = Field(default=20, ge=5, le=60, description="Target frame rate per second")
    resolution: ResolutionType = Field(
        default="720p",
        description="Target stream resolution ('1080p', '720p', '540p', '480p')"
    )
    mode: Optional[Literal["local", "remote"]] = Field(
        default="local",
        description="Connection mode ('local' for LAN-only or 'remote' for Internet NAT traversal)"
    )


class StreamAnswerResponse(BaseModel):
    """Agent WebRTC SDP answer response for media transport negotiation."""
    sdp: str = Field(description="WebRTC SDP answer string generated by Windows agent")
    type: Literal["answer"] = Field(default="answer", description="SDP message type")
    status: str = Field(default="streaming", description="Active streaming status")
    fps: int = Field(description="Negotiated stream frame rate")
    resolution: str = Field(description="Negotiated stream resolution")


class StreamStopResponse(BaseModel):
    """Response confirming screen-sharing session termination."""
    status: str = Field(default="stopped", description="Stream status")
    message: str = Field(description="Detailed confirmation message")


class StreamStatusResponse(BaseModel):
    """Current screen sharing status on the host laptop."""
    is_streaming: bool = Field(description="Whether a screen-sharing session is currently active")
    client_id: Optional[str] = Field(default=None, description="Identifier of the connected client if active")
    uptime_seconds: Optional[float] = Field(default=None, description="Duration of current stream session in seconds")
    fps: Optional[int] = Field(default=None, description="Active stream frame rate")
    resolution: Optional[str] = Field(default=None, description="Active stream resolution")
